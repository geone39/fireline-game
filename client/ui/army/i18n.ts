/** Ключи подписей, которых нет в content/strings (для запроса в content и проверки полноты). */
export const EXTRA_KEYS: Record<Lang, readonly string[]> = { ru: Object.keys(EXTRAS.ru), en: Object.keys(EXTRAS.en) };

/**
 * strings — объединённые content/strings/<lang>/{names,army}.yaml (key → текст). Ключ из content приоритетнее EXTRAS;
 * неизвестный ключ показывается как есть.
 */
export function createArmyT(lang: Lang, strings: Readonly<Record<string, string>>): T {
  const extras = EXTRAS[lang];
  return (key, vars) => {
    let s = strings[key] ?? extras[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
